"""Shared helpers for the STU-04 tests (contract: workflow/specs/STU-04/plan.md).

Attempts are created through the STU-02 HTTP endpoints. Rows that the HTTP flow cannot produce (an
attempt with fewer than three answers, several submitted attempts with chosen timestamps) are
inserted by SQL with the `practice_attempt` columns named in the plan.
"""
import json
import uuid

from auth_helpers import call
from fake_sets import FIXTURE_SET_ID
from stu01_helpers import sql

SET_ID = FIXTURE_SET_ID
SET_TITLE = "Software engineering basics"
BASICS_TOPIC = "66666666-6666-4666-8666-666666666661"
TOPIC_NAME = "Software engineering basics"
KEY = {"q1": "a", "q2": "b", "q3": "c"}
WRONG = {"q1": "b", "q2": "a", "q3": "a"}
QUESTION_TEXTS = [
    "What should a well-designed function have?",
    "To catch regressions when code changes",
    "values = [1, 2, 3]",
]
EXPLANATIONS = [
    "One focused responsibility makes a function easier to understand, test and change.",
    "Tests protect expected behaviour and can catch regressions introduced by later changes.",
    "len returns the number of items. The list contains three items.",
]
FORBIDDEN_IN_BODY = ["correct_choice", "explanation", "key_version", "attempt_id", "student_id",
                     "correct_question_ids", '"answers"', '"q1"', '"q2"', '"q3"', '"choices"']
EMPTY = {
    "lessons": {"totals": {"lesson_count": 0, "completed_count": 0}, "courses": [], "recent": []},
    "practice": {"sets": [], "average_latest_percent": None},
    "topics": {"rule": {"min_answers": 3, "weak_below_percent": 60}, "items": []},
}


def answers_with(n_correct):
    """A full answer map with exactly `n_correct` correct answers (0 to 3)."""
    out = {}
    for i, q in enumerate(["q1", "q2", "q3"]):
        out[q] = KEY[q] if i < n_correct else WRONG[q]
    return out


def start(student, set_id=SET_ID):
    r = call("POST", f"/api/practice-sets/{set_id}/attempts", student)
    assert r.status_code == 201, r.text
    return r.json()["attempt_id"]


def save(aid, student, answers):
    return call("PUT", f"/api/attempts/{aid}/answers", student, {"answers": answers})


def submit(aid, student):
    return call("POST", f"/api/attempts/{aid}/submit", student)


def submitted(student, n_correct):
    """Create, answer and submit one attempt with `n_correct` correct answers; return its id."""
    aid = start(student)
    assert save(aid, student, answers_with(n_correct)).status_code == 200
    r = submit(aid, student)
    assert r.status_code == 200, r.text
    return aid


def progress(student, path="/api/progress", **kw):
    return call("GET", path, student, **kw)


def body_of(student):
    r = progress(student)
    assert r.status_code == 200, r.text
    return r.json()


def only_set(body):
    assert len(body["practice"]["sets"]) == 1, body["practice"]
    return body["practice"]["sets"][0]


def topic_item(body, name=TOPIC_NAME):
    items = [i for i in body["topics"]["items"] if i["topic"]["name"] == name]
    assert len(items) == 1, body["topics"]
    return items[0]


def insert_attempt(student, *, answers, correct_ids, status="submitted", set_id=SET_ID,
                   submitted_at="2026-03-01T10:00:00Z", total=3, key_version="v1"):
    """Insert a practice_attempt row directly; returns its id. `seq` is generated by the database."""
    aid = "t-" + uuid.uuid4().hex[:20]
    if status == "submitted":
        sql("INSERT INTO practice_attempt(id, student_id, set_id, status, answers, score_correct, score_total, "
            "key_version, correct_question_ids, submitted_at) VALUES (%s, %s, %s, 'submitted', %s::jsonb, %s, %s, "
            "%s, %s::jsonb, %s::timestamptz)",
            (aid, str(student), set_id, json.dumps(answers), len(correct_ids), total, key_version,
             json.dumps(correct_ids), submitted_at))
    else:
        sql("INSERT INTO practice_attempt(id, student_id, set_id, status, answers) VALUES (%s, %s, %s, "
            "'in_progress', %s::jsonb)", (aid, str(student), set_id, json.dumps(answers)))
    return aid


def attempt_rows(student, set_id=None):
    q = ("SELECT id, status, answers, score_correct, score_total, key_version, correct_question_ids, "
         "submitted_at FROM practice_attempt WHERE student_id = %s")
    params = [str(student)]
    if set_id:
        q += " AND set_id = %s"
        params.append(set_id)
    return sql(q + " ORDER BY seq", tuple(params))
